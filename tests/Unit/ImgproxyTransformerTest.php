<?php

declare(strict_types=1);

use craft\elements\Asset;
use craft\errors\ImageTransformException;
use craft\helpers\FileHelper;
use craft\helpers\ImageTransforms;
use craft\imagetransforms\ImageTransformer;
use craft\models\ImageTransform;
use craft\models\ImageTransformIndex;
use GuzzleHttp\Client;
use GuzzleHttp\Exception\ServerException;
use GuzzleHttp\Handler\MockHandler;
use GuzzleHttp\HandlerStack;
use GuzzleHttp\Psr7\PumpStream;
use GuzzleHttp\Psr7\Response;
use SomehowDigital\Craft\ImgProxy\imagetransforms\ImgproxyTransformer;
use yii\base\NotSupportedException;

/**
 * The content of the transforms imgproxy generates in the tests.
 */
const TRANSFORMED_IMAGE = 'webp image';

/**
 * Answers the requests of Craft's HTTP client with the responses, in order.
 *
 * @param list<Response> $responses
 */
function fakeImgproxy(array $responses = []): MockHandler
{
	$handler = new MockHandler($responses);

	Craft::$container->set(Client::class, static fn(): Client => new Client(['handler' => HandlerStack::create($handler)]));

	return $handler;
}

/**
 * Generates the transform of the index, as Craft does once it has detected the format.
 */
function generate(Asset $asset, ImageTransformIndex $index): void
{
	$transformer = Craft::createObject(ImgproxyTransformer::class);

	(new ReflectionMethod($transformer, 'generateTransformedImage'))->invoke($transformer, $asset, $index);
}

/**
 * An index of a transform to 300x200, indexed for the transformer and with the format Craft detected.
 */
function transformIndex(string $transformer = ImgproxyTransformer::class): ImageTransformIndex
{
	return new ImageTransformIndex([
		'transformer' => $transformer,
		'transformString' => '_300x200_crop_center-center_none',
		'filename' => 'image.webp',
		'detectedFormat' => 'webp',
	]);
}

/**
 * The path of the filesystem of the volume, which is removed again after the test.
 */
function volumePath(): string
{
	return Craft::$app->getPath()->getTempPath() . '/volume';
}

afterEach(function (): void {
	FileHelper::removeDirectory(volumePath());
});

it('stores the transform generated by imgproxy', function (): void {
	$handler = fakeImgproxy([new Response(200, ['Content-Type' => 'image/webp'], TRANSFORMED_IMAGE)]);
	$index = transformIndex();

	generate($this->asset(['id' => 1, 'path' => volumePath(), 'folderPath' => 'photos/']), $index);

	expect(file_get_contents(volumePath() . '/photos/_300x200_crop_center-center_none/1/image.webp'))->toBe(TRANSFORMED_IMAGE);
	expect(urlOptions((string) $handler->getLastRequest()?->getUri()))->toBe(['rs:fill:300:200:1', 'q:70', 'f:webp']);
	expect($index->getTransform()->format)->toBeNull();
});

it('stores nothing when imgproxy fails', function (): void {
	fakeImgproxy([new Response(500)]);

	expect(fn() => generate($this->asset(['id' => 1, 'path' => volumePath()]), transformIndex()))->toThrow(ServerException::class);
	expect(is_dir(volumePath()))->toBeFalse();
});

it('stores nothing when imgproxy returns no image', function (): void {
	fakeImgproxy([new Response(200, ['Content-Type' => 'text/html'], '<html></html>')]);

	expect(fn() => generate($this->asset(['id' => 1, 'path' => volumePath()]), transformIndex()))
		->toThrow(ImageTransformException::class, 'imgproxy returned no image.');
	expect(is_dir(volumePath()))->toBeFalse();
});

it('stores nothing when the body of imgproxy cannot be read as a stream', function (): void {
	fakeImgproxy([new Response(200, ['Content-Type' => 'image/webp'], new PumpStream(static fn(): false => false))]);

	expect(fn() => generate($this->asset(['id' => 1, 'path' => volumePath()]), transformIndex()))
		->toThrow(ImageTransformException::class, 'imgproxy returned no readable body.');
	expect(is_dir(volumePath()))->toBeFalse();
});

it("leaves transforms indexed for Craft's transformer to Craft", function (): void {
	$handler = fakeImgproxy();
	FileHelper::writeToFile(volumePath() . '/image.png', base64_decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII=', true));
	$index = transformIndex(ImageTransformer::class);
	$index->filename = 'image.png';
	$index->detectedFormat = 'png';

	generate($this->asset(['id' => 1, 'path' => volumePath(), 'filename' => 'image.png']), $index);

	expect($handler->getLastRequest())->toBeNull();
	expect(getimagesize(volumePath() . '/_300x200_crop_center-center_none/image.png'))->toMatchArray([0 => 300, 1 => 200]);
});

/**
 * Has the transformer find the index of a transform of the asset with the ID 1 without a database, like Craft does for
 * eager-loaded transforms, with the generated file in place.
 */
function eagerLoad(ImgproxyTransformer $transformer, ImageTransform $transform): string
{
	$transformString = ImageTransforms::getTransformString($transform);
	$path = $transformString . '/1/image.webp';

	FileHelper::writeToFile(volumePath() . '/' . $path, TRANSFORMED_IMAGE);

	(new ReflectionProperty(ImageTransformer::class, 'eagerLoadedTransformIndexes'))->setValue($transformer, [
		'1:' . $transformString . ':webp' => [
			'assetId' => 1,
			'transformer' => ImgproxyTransformer::class,
			'transformString' => $transformString,
			'filename' => 'image.webp',
			'format' => 'webp',
			'fileExists' => true,
		],
	]);

	return $path;
}

it('stores the transforms of the store mode with the settings applied', function (): void {
	imageFormats(['jpg', 'heic']);
	$this->settings(['mode' => 'store', 'fallbackFormat' => 'webp']);
	$transformer = Craft::createObject(ImgproxyTransformer::class);
	$asset = $this->asset(['id' => 1, 'path' => volumePath(), 'filename' => 'image.heic']);
	$transform = new ImageTransform(['width' => 120, 'height' => 80]);

	$path = eagerLoad($transformer, $transform);

	// Only the index with the fallback format is eager-loaded, so the URL proves the format was applied.
	expect($transformer->getTransformUrl($asset, $transform, false))->toEndWith('/' . $path);
});

it('leaves volumes without public transform URLs to Craft', function (): void {
	$this->settings(['mode' => 'store']);
	$transformer = Craft::createObject(ImgproxyTransformer::class);

	expect(fn() => $transformer->getTransformUrl($this->asset(['hasUrls' => false]), new ImageTransform(['width' => 300]), false))
		->toThrow(NotSupportedException::class);
});
